"""Разбор ключей объектов MinIO.

Файлы загружаются с ключом `{направление}/{uuid4.hex}-{имя_файла}`
(pricelists/, specifications/), где префикс нужен против коллизий имён.
Для отображения в списках обратно извлекается исходное имя файла.
"""


class StoredFileKey:
    """Исходное имя файла из ключа объекта MinIO."""

    @staticmethod
    def original_name(file_key: str) -> str:
        """Вернуть имя файла из ключа: отсечь направление и uuid-префикс.

        Префикс — 32 hex-символов без дефисов, поэтому достаточно первого
        дефиса после имени объекта: в имени файла дефисы сохраняются.
        """
        name = file_key.rsplit("/", 1)[-1]
        _, _, tail = name.partition("-")
        return tail or name
